if (!function_exists('ui_illustration')) {
    /**
     * Renderiza ilustraciones SVG inline desde archivos locales.
     *
     * @param array<string,string|int|bool|null> $attrs
     */
    function ui_illustration(string $name, string $class = '', array $attrs = []): string {
        static $illustrations = [
            'empty-search' => 'app/Support/illustrations/empty-search.svg',
        ];

        $relativePath = $illustrations[$name] ?? null;
        if ($relativePath === null) {
            return '';
        }

        $path = base_path($relativePath);
        if (!is_file($path)) {
            return '';
        }

        $svg = trim((string)@file_get_contents($path));
        if ($svg === '') {
            return '';
        }

        $svg = preg_replace_callback(
            '/<svg\b([^>]*)>/i',
            static function (array $matches) use ($class, $attrs): string {
                $tagAttrs = $matches[1];

                if ($class !== '') {
                    if (preg_match('/\bclass=(["\'])(.*?)\1/i', $tagAttrs, $classMatch)) {
                        $mergedClass = trim($classMatch[2] . ' ' . $class);
                        $tagAttrs = preg_replace(
                            '/\bclass=(["\'])(.*?)\1/i',
                            'class="' . e($mergedClass) . '"',
                            $tagAttrs,
                            1
                        ) ?? $tagAttrs;
                    } else {
                        $tagAttrs .= ' class="' . e($class) . '"';
                    }
                }

                foreach ($attrs as $attr => $value) {
                    if ($attr === 'class' || $value === null || $value === false) {
                        continue;
                    }

                    if ($value === true) {
                        $tagAttrs .= ' ' . $attr;
                        continue;
                    }

                    $tagAttrs .= ' ' . $attr . '="' . e((string)$value) . '"';
                }

                return '<svg' . $tagAttrs . '>';
            },
            $svg,
            1
        ) ?? $svg;

        return $svg;
    }
}

