if (!function_exists('product_cover_url')) {
    /**
     * Devuelve la URL de imagen de portada del producto con compatibilidad "legacy".
     * Prioridad:
     * 1) image_url | cover_url | image | photo (si parecen URL absolutas o relativas)
     * 2) /uploads/products/{sku}/cover.*  (jpg|jpeg|png|webp)
     * 3) /uploads/products/{slug}/cover.*
     * 4) /uploads/products/{sku}.{ext} (jpg|jpeg|png|webp)
     * 5) placeholder
     */
    function product_cover_url(array $p): string {
        $candidates = [];
        foreach (['thumb','image_url','cover_url','image','photo'] as $k) {
            if (!empty($p[$k]) && is_string($p[$k])) {
                $candidates[] = $p[$k];
            }
        }

        // 1) direct fields that look like urls/paths
        foreach ($candidates as $u) {
            $s = trim($u);
            if ($s === '') continue;
            if (preg_match('#^(https?:)?//#', $s) || $s[0] === '/') {
                return $s;
            }
            if (preg_match('#^(assets/|uploads/)#', $s)) {
                // assets â†’ usar asset(); uploads â†’ base_url
                if (strpos($s, 'assets/') === 0) return asset($s);
                return base_url('/' . ltrim($s, '/'));
            }
        }

        // 2) filesystem conventions
        $sku  = $p['sku']  ?? null;
        $slug = $p['slug'] ?? ($p['product_slug'] ?? null);
        $exts = ['jpg','jpeg','png','webp'];
        $base = rtrim(public_path(), '/\\');

        $fs_candidates = [];
        if ($sku) {
            foreach ($exts as $ext) {
                $fs_candidates[] = "/uploads/products/$sku/cover.$ext";
                $fs_candidates[] = "/uploads/products/$sku.$ext";
            }
        }
        if ($slug) {
            foreach ($exts as $ext) {
                $fs_candidates[] = "/uploads/products/$slug/cover.$ext";
            }
        }
        foreach ($fs_candidates as $webPath) {
            $abs = $base . $webPath;
            if (is_file($abs)) return $webPath; // devolver ruta web
        }

        // 3) placeholder
        return asset('img/placeholder.svg');
    }
}

