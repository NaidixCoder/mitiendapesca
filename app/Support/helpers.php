        ) {
            return;
        }

        $token = $_POST['_csrf'] ?? $_POST['csrf'] ?? $_SERVER['HTTP_X_CSRF_TOKEN'] ?? null;
        if (!csrf_check(is_string($token) ? $token : null)) {
            $accept = (string)($_SERVER['HTTP_ACCEPT'] ?? '');
            $xrw = (string)($_SERVER['HTTP_X_REQUESTED_WITH'] ?? '');
            $wantsJson = stripos($accept, 'application/json') !== false
                || strcasecmp($xrw, 'XMLHttpRequest') === 0;

            if ($wantsJson) {
                $protocol = (string)($_SERVER['SERVER_PROTOCOL'] ?? 'HTTP/1.1');
                header($protocol . ' 419 Authentication Timeout', true, 419);
                header('Content-Type: application/json; charset=utf-8');
                echo json_encode([
                    'ok' => false,
                    'error' => 'csrf_invalid',
                    'message' => 'CSRF token invalido o ausente.',
                ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
                exit;
            }

            $protocol = (string)($_SERVER['SERVER_PROTOCOL'] ?? 'HTTP/1.1');
