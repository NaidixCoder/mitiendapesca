if (!function_exists('db_has_column')) {
    function db_has_column(string $table, string $column): bool {
        static $cache = [];
        $key = $table.'.'.$column;
        if (array_key_exists($key, $cache)) return (bool)$cache[$key];
        try {
            $db = db();
            $st = $db->prepare("SHOW COLUMNS FROM {$table} LIKE ?");
            $st->execute([$column]);
            $ok = (bool)$st->fetch(\PDO::FETCH_ASSOC);
            $cache[$key] = $ok;
            return $ok;
        } catch (\Throwable $e) {
            $cache[$key] = false;
            return false;
        }
    }
}

