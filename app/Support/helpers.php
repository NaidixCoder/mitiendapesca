/* Tiempo relativo en espanol (asume fecha en UTC) */
if (!function_exists('time_ago_es')) {
    function time_ago_es(?string $datetime, string $dbTimezone = 'UTC'): string {
        if (!$datetime) return '';
        try {
            $tz  = new \DateTimeZone($dbTimezone ?: 'UTC');
            $dt  = new \DateTimeImmutable($datetime, $tz);
            $now = new \DateTimeImmutable('now', $tz);

            $diff = $now->getTimestamp() - $dt->getTimestamp();
            if ($diff < 0) $diff = 0;

            if ($diff < 30) return 'recien';
            if ($diff < 60) return 'hace ' . $diff . ' s';

            $m = intdiv($diff, 60);
            if ($m < 60) return 'hace ' . $m . ' min';

            $h = intdiv($m, 60);
            if ($h < 24) return 'hace ' . $h . ' h';

            $d = intdiv($h, 24);
            if ($d == 1) return 'ayer';
            return 'hace ' . $d . ' dias';
        } catch (\Throwable $e) {
            return '';
        }
    }
}





