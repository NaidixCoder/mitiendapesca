/**
 * asset(): URL a assets con cache-busting (?v=filemtime)
 * - Si viene URL absoluta, la deja igual.
 * - Prefija /assets si no está.
 * - Soporta ASSET_URL (CDN) y APP_ASSET_VERSION para forzar versiÃ³n global.
 */
if (!function_exists('asset')) {
    function asset(string $path): string {
        // Absoluta â†’ no tocar
        if (preg_match('#^https?://#i', $path)) return $path;

        // Normalizar prefijo
        $p = '/' . ltrim($path, '/');
        if (strpos($p, '/assets/') !== 0) $p = '/assets' . $p;

        // Â¿CDN/Host para assets?
        $assetBase = rtrim((string)env_safe('ASSET_URL', ''), '/');
        $urlBase   = $assetBase !== '' ? $assetBase : rtrim(base_url('/assets'), '/');
        $rel       = ltrim(substr($p, strlen('/assets')), '/');

        // Resolver ruta local para filemtime()
        $local = public_path() . '/assets/' . $rel;
        if (defined('APP_ASSET_VERSION')) {
            $ver = (string)APP_ASSET_VERSION;
        } else {
            $ver = is_file($local) ? (string)filemtime($local) : (string)time();
        }

        $sep = (strpos($urlBase . '/' . $rel, '?') === false) ? '?' : '&';
        return $urlBase . '/' . $rel . $sep . 'v=' . $ver;
    }
}

/** URL actual (sin duplicar subcarpeta) */
if (!function_exists('current_url')) {
    function current_url(bool $withQuery = false): string {
        $base = rtrim(base_url(), '/');
        $uri  = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/';
        $uri  = str_replace('\\', '/', $uri);
        $scriptDir = rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? '')), '/');
        if ($scriptDir && $scriptDir !== '/') {
            $uri = preg_replace('#^' . preg_quote($scriptDir, '#') . '#', '', $uri);
            if ($uri === '') $uri = '/';
        }
        $out = $base . ($uri === '/' ? '' : $uri);
        if ($withQuery && !empty($_SERVER['QUERY_STRING'])) $out .= '?' . $_SERVER['QUERY_STRING'];
        return $out;
    }
}

