                'login_url' => url('/login') . '?next=' . rawurlencode($next),
            ], 401);
        };

        $svSess = (int)($_SESSION['sv'] ?? 0);

        try {
            $stmt = db()->prepare('SELECT session_version, role, name, email, avatar_url FROM users WHERE id=? LIMIT 1');
            $stmt->execute([$uid]);
            $row = $stmt->fetch(\PDO::FETCH_ASSOC);

            // Usuario eliminado / inexistente => revocar
            if (!$row) {
                $revoke('user_not_found');
            }

            // Activity ping (para estado Online/Offline en Admin)
            try {
                db()->prepare('UPDATE users SET last_activity_at = NOW() WHERE id=?')->execute([$uid]);
            } catch (\Throwable $e) {
                // ignore si la columna aÃºn no existe
            }


            $svDb = (int)($row['session_version'] ?? 0);

            // SesiÃ³n vieja: setear sv (primera vez) y sincronizar datos bÃ¡sicos
            if ($svSess <= 0) {
                $_SESSION['sv'] = $svDb;
                $svSess = $svDb;
            }

            // session_version distinto => revocado
            if ($svSess !== $svDb) {
                $revoke('session_revoked');
            }

            // Sync: si te quitan admin, esto se refleja sin depender del cliente
            $_SESSION['urole'] = (string)($row['role'] ?? 'customer');
            if (!empty($row['name']))  $_SESSION['uname'] = (string)$row['name'];
            if (!empty($row['email'])) $_SESSION['email'] = (string)$row['email'];
            if (array_key_exists('avatar_url', $row)) $_SESSION['avatar_url'] = $row['avatar_url'];

        } catch (\Throwable $e) {
            // Seguridad-first: si no podemos validar contra DB, invalidamos.
            $revoke('auth_db_unavailable');
        }
    }
}


