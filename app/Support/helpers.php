/** Renderiza pÃ¡gina en app/Views/pages/{name}.php con head/header/footer */
if (!function_exists('render_page')) {
    function render_page(string $name, array $vars = []): void {
        static $renderDepth = 0;
        $renderDepth++;

        // Guard: si se llama render_page() dentro de otro render_page(), evitamos HTML duplicado/anidado.
        // En esos casos rendereamos SOLO el contenido de la vista (sin head/header/footer).
        if ($renderDepth > 1) {
            if (function_exists('log_error')) {
                log_error('Nested render_page detectado: ' . $name);
            }
            $viewsDir = base_path('app/Views');
            $pageFile = $viewsDir . '/pages/' . $name . '.php';
            if (!empty($vars)) extract($vars, EXTR_SKIP);
            if (is_file($pageFile)) {
                include $pageFile;
            } else {
                http_response_code(404);
                echo '<main class="container mx-auto p-6"><h1>Vista no encontrada</h1><p>' . e($name) . '</p></main>';
            }
            $renderDepth--;
            return;
        }

        $viewsDir = base_path('app/Views');
        $head     = $viewsDir . '/partials/head.php';
        $header   = $viewsDir . '/partials/header/header.php';
        $flash    = $viewsDir . '/partials/flash.php'; // Ã¢Å“â€¦ NUEVO
        $toastHost = $viewsDir . '/partials/components/toast_host.php';
        $footer   = $viewsDir . '/partials/footer.php';
        $scripts  = $viewsDir . '/partials/scripts.php';
        $htmlEnd  = $viewsDir . '/partials/html_end.php';
        $pageFile = $viewsDir . '/pages/' . $name . '.php';

        if (!empty($vars)) extract($vars, EXTR_SKIP);

        // Admin layout baseline: resolve before head/header include.
        $isAdminPage = str_starts_with($name, 'admin/');
        if ($isAdminPage) {
            if (!isset($hideHeader)) $hideHeader = true;
            if (!isset($hideFooter)) $hideFooter = true;
            if (!isset($pageId) || $pageId === '') {
                $slug = trim(substr($name, strlen('admin/')), '/');
                $slug = str_replace(['/', '_'], '-', $slug);
                $pageId = $slug !== '' ? ('admin-' . $slug) : 'admin';
            }
        }

        echo "<!-- RENDER start: " . e($name) . " -->\n";
        if (is_file($head)) include $head;
        if (!(bool)($hideHeader ?? false) && is_file($header)) include $header;

        // Ã¢Å“â€¦ Flash global (mensajes de sesiÃ³n)
        // Checkout renderiza flash inline dentro de la pÃ¡gina para mÃ¡xima visibilidad.
        if (($pageId ?? '') !== 'checkout' && is_file($flash)) include $flash;
        if (is_file($toastHost)) include $toastHost;

        if ($isAdminPage && is_file($pageFile)) {
            $GLOBALS['_admin_master_capture'] = true;
            $GLOBALS['_admin_master_header'] = '';
            ob_start();
            try {
                include $pageFile;
                $adminMasterContent = ob_get_clean();
            } catch (\Throwable $adminMasterError) {
                ob_end_clean();
                unset($GLOBALS['_admin_master_capture'], $GLOBALS['_admin_master_header']);
                throw $adminMasterError;
            }
            unset($GLOBALS['_admin_master_capture']);
            include $viewsDir . '/layouts/admin.php';
            unset($GLOBALS['_admin_master_header']);
        } elseif (is_file($pageFile)) include $pageFile;
        else {
            http_response_code(404);
            echo '<main class="container mx-auto p-6"><h1>Vista no encontrada</h1><p>' . e($name) . '</p></main>';
        }
        if (!(bool)($hideFooter ?? false) && is_file($footer)) include $footer;
        if (is_file($scripts)) include $scripts;
        if (is_file($htmlEnd)) include $htmlEnd;
        echo "\n<!-- RENDER end: " . e($name) . " -->\n";

        $renderDepth--;
    }
}


/** Incluye partial exacto (sin "magia") */
if (!function_exists('section')) {
    function section(string $path, array $vars = []): void {
        if (!empty($vars)) extract($vars, EXTR_SKIP);
        $root = rtrim(base_path('app/Views'), '/\\') . '/';

        $candidates = [
            $root . ltrim($path, '/') . '.php',
            $root . 'partials/' . ltrim($path, '/') . '.php', // fallback
        ];

        foreach ($candidates as $file) {
            if (is_file($file)) { include $file; return; }
        }
        echo '<!-- section missing: ' . e($path) . ' -->';
    }
}

