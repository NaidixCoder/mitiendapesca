if (!function_exists('redirect')) {
    function redirect(string $path, int $status = 302): void {
        // Asegurar que lo que se guardÃ³ en sesiÃ³n (flash, etc.) se escriba antes de salir.
        if (session_status() === PHP_SESSION_ACTIVE) {
            @session_write_close();
        }
        // Normaliza paths internos para no duplicar basepath (local subcarpeta)
        if (!preg_match('#^https?://#i', $path)) {
            $scriptDir = rtrim(dirname($_SERVER['SCRIPT_NAME'] ?? '/index.php'), '/');
            if ($scriptDir !== '' && $scriptDir !== '/' && str_starts_with($path, $scriptDir.'/')) {
                $path = substr($path, strlen($scriptDir));
                if ($path === '') { $path = '/'; }
            }
        }

        $location = (preg_match('#^https?://#i', $path)) ? $path : base_url($path);
        http_response_code($status);
        header('Location: ' . $location);
        exit;
    }
}

/* ==================== Redirect safety helpers ==================== */

// Sanitiza una URL interna (path + query) para evitar open-redirect.
// Acepta Ãºnicamente paths relativos al sitio (sin esquema, sin host).
if (!function_exists('sanitize_next_url')) {
    function sanitize_next_url(string $next, string $fallback = '/cuenta'): string {
        $next = trim($next);
        if ($next === '') return $fallback;
        if (strlen($next) > 2048) return $fallback;

        // Evitar URLs absolutas / esquemas
        if (str_contains($next, '://') || str_starts_with($next, '//')) {
            return $fallback;
        }

        // Evitar CRLF / header injection
        $next = str_replace(["\r", "\n"], '', $next);

        // Normalizar a path interno
        if (!str_starts_with($next, '/')) {
            $next = '/' . $next;
        }

        // Endpoints no navegables (POST-only) nunca deben usarse como destino de login.
        $nonNavigable = [
            '/cuenta/favoritos/toggle',
        ];
        foreach ($nonNavigable as $blockedPath) {
            if ($next === $blockedPath || str_starts_with($next, $blockedPath . '?')) {
                return $fallback;
            }
        }

        // Quitar basepath si viene incluido en REQUEST_URI (evita duplicar /mi-pesca/public_html ...)
        $scriptName = str_replace('\\', '/', (string)($_SERVER['SCRIPT_NAME'] ?? ''));
        $scriptDir  = rtrim(dirname($scriptName), '/');
        if ($scriptDir !== '' && $scriptDir !== '/') {
            // Caso: next == /mi-pesca/public_html
            if ($next === $scriptDir) {
                $next = '/';
            }
            // Caso: next empieza con el basepath + "/"
            while (str_starts_with($next, $scriptDir . '/')) {
                $next = substr($next, strlen($scriptDir));
                if ($next === '') { $next = '/'; break; }
            }
        }


        return $next;
    }
}

