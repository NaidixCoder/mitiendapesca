if (!function_exists('qs_preserve')) {
    /**
     * Preserva el query actual y aplica overrides.
     * Filtra null/'' y setea page=1 si cambiÃ¡s filtros.
     *
     * @param array $overrides
     * @param array $keepKeys  Claves que se preservan; por defecto preserva todas.
     */
    function qs_preserve(array $overrides = [], array $keepKeys = []): string {
        $cur = $_GET ?? [];
        if ($keepKeys) {
            $cur = array_intersect_key($cur, array_flip($keepKeys));
        }
        $q = array_merge($cur, $overrides);
        // limpiar vacÃ­os
        $q = array_filter($q, fn($v) => $v !== null && $v !== '');
        return '?' . http_build_query($q);
    }
}
