    function dt_local_from_utc(?string $datetime, string $format = 'Y-m-d H:i', string $dbTimezone = 'UTC', ?string $appTimezone = null): string {
        if (!$datetime) return '';
        try {
            $dbTz  = new \DateTimeZone($dbTimezone ?: 'UTC');
            $appTz = new \DateTimeZone($appTimezone ?: (defined('APP_TIMEZONE') ? APP_TIMEZONE : date_default_timezone_get()));
