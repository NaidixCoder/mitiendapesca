 * base_url(): detecta correctamente subcarpeta (public_html) y evita CORS si APP_URL coincide con el host actual.
 */
if (!function_exists('base_url')) {
    function base_url(string $path = ''): string {
        $envUrl   = rtrim((string)env_safe('APP_URL', ''), '/');
        $envHost  = $envUrl ? (parse_url($envUrl, PHP_URL_HOST) ?: '') : '';
        $currHost = $_SERVER['HTTP_HOST'] ?? '';

        $useEnv = $envUrl !== '' && $envHost !== '' && $currHost !== '' && strcasecmp($envHost, $currHost) === 0;

        if ($useEnv) {
            // Si APP_URL no incluye subcarpeta (local), completamos con el directorio real del script.
            // Ej: APP_URL=https://localhost y SCRIPT_NAME=/mi-pesca/public_html/index.php => base=https://localhost/mi-pesca/public_html
            $envPath = (string)(parse_url($envUrl, PHP_URL_PATH) ?: '');
            $envPath = rtrim($envPath, '/');
            $scriptName = str_replace('\\', '/', $_SERVER['SCRIPT_NAME'] ?? '');
            $scriptDir  = rtrim(dirname($scriptName), '/');

            if (($envPath === '' || $envPath === '/') && $scriptDir !== '' && $scriptDir !== '/') {
                $base = rtrim($envUrl, '/') . $scriptDir;
            } else {
                $base = $envUrl;
            }
        } else {
            $https  = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (($_SERVER['SERVER_PORT'] ?? null) == 443);
            $scheme = $https ? 'https' : 'http';
            $host   = $currHost ?: 'localhost';
            $scriptName = str_replace('\\', '/', $_SERVER['SCRIPT_NAME'] ?? '');
            $scriptDir  = rtrim(dirname($scriptName), '/');
            $base  = $scheme . '://' . $host . ($scriptDir && $scriptDir !== '/' ? $scriptDir : '');
        }

        $path = '/' . ltrim($path, '/');
        return rtrim($base, '/') . ($path === '/' ? '' : $path);
    }
}

