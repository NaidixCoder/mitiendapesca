        $path = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/';
        if (
            ($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST'
            && str_ends_with($path, '/oauth/google')
