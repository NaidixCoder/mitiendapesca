<?php
declare(strict_types=1);
require dirname(__DIR__, 2) . '/vendor/autoload.php';
use App\Repositories\Suppliers\ProveedorRepository;
use App\Services\Suppliers\ProveedorService;
$pdo = new PDO('sqlite::memory:');
$pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
$pdo->sqliteCreateFunction('NOW', static fn() => date('Y-m-d H:i:s'));
$pdo->exec('CREATE TABLE suppliers (id INTEGER PRIMARY KEY AUTOINCREMENT, nombre TEXT, cuit TEXT UNIQUE, email TEXT, telefono TEXT, condicion_iva TEXT, is_active INTEGER, created_at TEXT, updated_at TEXT)');
$repo = new ProveedorRepository($pdo);
$service = new ProveedorService($repo);
$passes = 0;
$check = static function(bool $condition, string $name) use (&$passes): void {
    if (!$condition) throw new RuntimeException("FAIL: $name");
    echo "PASS: $name\n"; $passes++;
};
$check($service->count() === 0, 'vacío');
$check(!$service->save(['nombre' => '', 'cuit'=>'123'])['ok'], 'requeridos/CUIT');
$check(!$service->save(['nombre'=>'Test', 'cuit'=>'20329642330','email'=>'invalido'])['ok'], 'email invalido');
$check(!$service->save(['nombre'=>'Test', 'cuit'=>'20329642330','condicion_iva'=>'intruso'])['ok'], 'IVA no permitido');
$check(!$service->save(['nombre'=>'Test', 'cuit'=>'20329642330','is_active'=>'33'])['ok'], 'estado no permitido');
$valid = ['nombre'=>'Proveedor Uno', 'cuit'=>'20329642330','email'=>'contacto@example.com','telefono'=>'341', 'condicion_iva'=>'monotributo','is_active'=>'1'];
$result = $service->save($valid);
$check($result['ok'], 'alta');
$id = (int)$result['id'];
$check($service->count() === 1, 'count activo');
$check(!$service->save($valid)['ok'], 'duplicado');
$check(count($service->list(['q'=>'Uno'])) === 1, 'búsqueda nombre');
$check(count($service->list(['q'=>'203296'])) === 1, 'búsqueda CUIT');
$check($service->save(array_merge($valid,['nombre'=>'Proveedor Dos']),$id)['ok'], 'edición');
$check($repo->findById($id)['nombre'] === 'Proveedor Dos', 'persistencia edición');
$check($service->delete($id), 'baja lógica');
$check(!$service->delete($id), 'baja idempotente');
$check($service->count() === 0 && $service->count(['status'=>'inactive']) === 1, 'filtro inactivos');
$check($service->count(['status'=>'all']) === 1, 'filtro todos');
$check($service->save($valid,$id)['ok'], 'reactivación');
$check($service->count() === 1, 'reactivado activo');
$check($service->count(['q'=>'inexistente']) === 0, 'búsqueda vacía');
echo "TOTAL: $passes/$passes\n";
